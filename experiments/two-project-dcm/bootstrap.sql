-- Privileged setup only. The CLI caller must pin ACCOUNTADMIN and secondary roles NONE.
-- Never use this role for DCM deployment.

CREATE ROLE IF NOT EXISTS BLZ_DCMX_4X6_FOUNDATION_DEPLOYER;
CREATE ROLE IF NOT EXISTS BLZ_DCMX_4X6_DOMAIN_DEPLOYER;
CREATE ROLE IF NOT EXISTS BLZ_DCMX_4X6_UNRELATED;

CREATE USER IF NOT EXISTS BLZ_DCMX_4X6_FOUNDATION_USER TYPE = SERVICE
  DEFAULT_ROLE = BLZ_DCMX_4X6_FOUNDATION_DEPLOYER;
CREATE USER IF NOT EXISTS BLZ_DCMX_4X6_DOMAIN_USER TYPE = SERVICE
  DEFAULT_ROLE = BLZ_DCMX_4X6_DOMAIN_DEPLOYER;
CREATE USER IF NOT EXISTS BLZ_DCMX_4X6_CONSUMER_USER TYPE = SERVICE;
CREATE USER IF NOT EXISTS BLZ_DCMX_4X6_UNRELATED_USER TYPE = SERVICE
  DEFAULT_ROLE = BLZ_DCMX_4X6_UNRELATED;

GRANT USAGE ON DATABASE SNOWFLAKE_LEARNING_DB TO ROLE BLZ_DCMX_4X6_FOUNDATION_DEPLOYER;
GRANT USAGE ON SCHEMA SNOWFLAKE_LEARNING_DB.DCM TO ROLE BLZ_DCMX_4X6_FOUNDATION_DEPLOYER;
GRANT CREATE DCM PROJECT, CREATE STAGE ON SCHEMA SNOWFLAKE_LEARNING_DB.DCM TO ROLE BLZ_DCMX_4X6_FOUNDATION_DEPLOYER;
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE BLZ_DCMX_4X6_FOUNDATION_DEPLOYER;
GRANT CREATE ROLE ON ACCOUNT TO ROLE BLZ_DCMX_4X6_FOUNDATION_DEPLOYER;

GRANT USAGE ON DATABASE SNOWFLAKE_LEARNING_DB TO ROLE BLZ_DCMX_4X6_DOMAIN_DEPLOYER;
GRANT USAGE ON SCHEMA SNOWFLAKE_LEARNING_DB.DCM TO ROLE BLZ_DCMX_4X6_DOMAIN_DEPLOYER;
GRANT CREATE DCM PROJECT, CREATE STAGE ON SCHEMA SNOWFLAKE_LEARNING_DB.DCM TO ROLE BLZ_DCMX_4X6_DOMAIN_DEPLOYER;
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE BLZ_DCMX_4X6_DOMAIN_DEPLOYER;
GRANT CREATE DATABASE ON ACCOUNT TO ROLE BLZ_DCMX_4X6_DOMAIN_DEPLOYER;

GRANT ROLE BLZ_DCMX_4X6_FOUNDATION_DEPLOYER TO USER BLZ_DCMX_4X6_FOUNDATION_USER;
GRANT ROLE BLZ_DCMX_4X6_DOMAIN_DEPLOYER TO USER BLZ_DCMX_4X6_DOMAIN_USER;
GRANT ROLE BLZ_DCMX_4X6_UNRELATED TO USER BLZ_DCMX_4X6_UNRELATED_USER;
